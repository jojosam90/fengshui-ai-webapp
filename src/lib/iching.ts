export interface Hexagram {
  number: number;
  name: string;
  fullName: string;
  upper: Trigram;
  lower: Trigram;
  symbol: string;
  judgment: string;
  meaning: string;
}

const HEXAGRAMS: Hexagram[] = DATA.map(([number, name, up, low, judgment, meaning]) => {
  const upper = TRIGRAMS[up];
  const lower = TRIGRAMS[low];
  return {
    number,
    name,
    fullName: up === low ? `${name}为${upper.image}` : `${upper.image}${lower.image}${name}`,
    upper,
    lower,
    symbol: String.fromCodePoint(0x4dc0 + number - 1),
    judgment,
    meaning,
  };
});

const trigramOf = (lines: number[]) =>
  Object.values(TRIGRAMS).find((t) => t.lines.every((v, i) => v === lines[i]))!;

/** lines: 自下而上 6 爻，1 阳 0 阴 */
export function hexagramFromLines(lines: number[]): Hexagram {
  const lower = trigramOf(lines.slice(0, 3));
  const upper = trigramOf(lines.slice(3, 6));
  return HEXAGRAMS.find((h) => h.upper === upper && h.lower === lower)!;
}

/**
 * 三钱法：每枚正面(字)为 3、背面为 2。
 * 6 老阴(变) · 7 少阳 · 8 少阴 · 9 老阳(变)
 */
export type LineValue = 6 | 7 | 8 | 9;

export function tossLine(): { coins: (2 | 3)[]; value: LineValue } {
  const buf = new Uint8Array(3);
  crypto.getRandomValues(buf);
  const coins = Array.from(buf, (b) => (b & 1 ? 3 : 2)) as (2 | 3)[];
  return { coins, value: (coins[0] + coins[1] + coins[2]) as LineValue };
}

export const isYang = (v: LineValue) => v === 7 || v === 9;
export const isChanging = (v: LineValue) => v === 6 || v === 9;

export const LINE_NAMES = ["初", "二", "三", "四", "五", "上"];

export function castResult(values: LineValue[]) {
  const primary = hexagramFromLines(values.map((v) => (isYang(v) ? 1 : 0)));
  const changing = values.map((v, i) => (isChanging(v) ? i : -1)).filter((i) => i >= 0);
  const changed = changing.length
    ? hexagramFromLines(values.map((v) => (isYang(v) !== isChanging(v) ? 1 : 0)))
    : null;
  const lineLabel = (i: number) => {
    const n = isYang(values[i]) ? "九" : "六";
    return i === 0 ? `初${n}` : i === 5 ? `上${n}` : `${n}${LINE_NAMES[i]}`;
  };
  return { primary, changed, changing, changingLabels: changing.map(lineLabel) };
}
